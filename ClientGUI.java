private void connectToServer() {
        try {
            String SERVER_ADDRESS = JOptionPane.showInputDialog("Enter Server IP:");
            if (SERVER_ADDRESS == null || SERVER_ADDRESS.trim().isEmpty()) return;
            socket = new Socket(SERVER_ADDRESS.trim(), SERVER_PORT);
            in_fromServer = new BufferedReader(new InputStreamReader(socket.getInputStream()));
            out_toServer = new PrintWriter(socket.getOutputStream(), true);

            Thread listener = new Thread(new ServerListenerGUI(in_fromServer, outputArea));
            listener.start();
            

            outputArea.append("Connected to server.\n");
            Connected = true;
        } catch (IOException e) {
            outputArea.append("Failed to connect.\n");
        }
    }

private void Register() {
        String username = JOptionPane.showInputDialog("Enter username:");
        String password = JOptionPane.showInputDialog("Enter password:");
        sendCommand(1);
        sendCommand(username+" ");
        sendCommand(password+" ");
    }

    private void login() {
        String username = JOptionPane.showInputDialog("Enter username:");
        String password = JOptionPane.showInputDialog("Enter password:");
        sendCommand(2);
        sendCommand(username+" ");
        sendCommand(password+" ");
    }

    private void reserve() {
        String slot = JOptionPane.showInputDialog("Enter slot (e.g., Room8-Friday-11AM):");
        
        sendCommand(3);
        sendCommand(slot);
    }

    private void cancel() {
        sendCommand(4);
        String choice = JOptionPane.showInputDialog("Enter reservation number to cancel (check output list):");
        if (choice != null) {
            sendCommand(choice);
        }
    }

    private void sendCommand(String cmd) {
        cmd = cmd+" ";
        if (out_toServer != null) out_toServer.println(cmd);
    }
    private void sendCommand(int cmd) {
        if (out_toServer != null) out_toServer.println(cmd);
    }
