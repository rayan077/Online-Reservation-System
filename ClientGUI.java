private class ButtonHandler implements ActionListener {
        @Override
        public void actionPerformed(ActionEvent evt) {
            if (Connected == true){
                Object source = evt.getSource();
                if (source == registerBtn) Register();
                else if (source == loginBtn) login();
                else if (source == reserveBtn) reserve();
                else if (source == cancelBtn) cancel();
                else if (source == profileBtn) sendCommand(5);
                else if (source == exitBtn) {
                    sendCommand("6");
                    outputArea.append("You have disconnected.\n");
                    Connected = false;
                    System.out.println("Client closed the GUI and disconnected.");
                    try {
                        if (socket != null) socket.close();
                }   catch (IOException e) {
                        e.printStackTrace();
                }
            }
            }
            else {
            outputArea.append("Connect First!\n");
            }
        }
    }
